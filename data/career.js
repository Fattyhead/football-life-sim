/* 租借：純玩家選擇，不是強制事件，也沒有失敗懲罰——跟 PATHS 的青訓淘汰是不同性質的機制，
   淘汰是生涯起點的一次性豪賭，租借是中生涯可以反覆考慮的低風險機會。
   兩種觸發方式：
     數值到門檻自動開放選項 — 屬性接近高一階 DP_TH 門檻時，租借選項出現，
       玩家可以主動申請租借去試試更高階聯賽。
     球隊事件觸發 — 敘事事件跳出「高階球隊詢問租借意願」，玩家選擇接受/拒絕。
   租借去向固定高一階（LOCAL→FEEDER、FEEDER→TOP5），期間套用租借目的地的 TRAINING_MULT。
   賽季結束時看租借期間表現：打得好可以留下（轉為正式轉會），打不好就回原隊，
   沒有屬性懲罰——回原隊繼續踢，跟出發前沒差別。 */
